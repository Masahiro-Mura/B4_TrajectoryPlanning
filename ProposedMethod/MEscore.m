function Me_score = MEscore(acc, jerk)
    %% 論文記載の一般集団向け統計モデル係数
    beta_0  = 1.0;      % 切片
    beta_A  = 2.297;    % 加速度の主効果
    beta_J  = -0.052;   % ジャークの主効果 (負の値は、短時間パルスが不快感を下げる傾向を反映) 
    
    %% 周辺車両の走行状況（前後方向の加減速）に合わせた項の選定
    % 1. 運動方向 (d): 0=前方(加速), 2=後方(減速) 
    % 論文では減速（後方パルス）時に不快感への感度が高まることが示されています。
    d = 0;      % 加速度が負（ブレーキ）の場合に方向フラグを立てる
    beta_d  = -0.005;   % 方向（後方）の主効果 
    beta_Ad = 0.247;    % 加速度と方向の交互作用（減速時の不快感増分） 

    % 2. 加減速プロファイル (p): 0=正弦波, 1=三角波 
    % 周辺車両の制御が一定のジャークを保つような波形であれば三角波（1）を選択します。
    % ここではより保守的な（不快感が高めに出る）正弦波（0）をデフォルトとします。
    p = 1;              
    beta_p  = -0.283;   % プロファイル（三角波）の主効果
    beta_Ap = -0.317;   % 加速度とプロファイルの交互作用

    %% 不快感スコア (ME_norm) の計算 
    A = abs(acc);
    J = abs(jerk);

    Me_score =  beta_0 ...
             + (beta_A  * A) ...
             + (beta_J  * J) ...
             + (beta_d      * d) ...
             + (beta_Ad * A * d) ...
             + (beta_p      * p) ...
             + (beta_Ap * A * p);

    % スコアが「Excellent (1.0)」を下回らないようガード 
    % Me_score = max(1.0, Me_score);
end